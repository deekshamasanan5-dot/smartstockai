export function calculateMockStats(products: Product[], alerts: ReorderAlert[]): DashboardStats {
  const totalInventoryValue = products.reduce((acc, p) => acc + (p.current_stock * p.cost_price), 0);
  const totalSKUs = products.length;
  const inStockCount = products.filter(p => p.status === 'in_stock').length;
  const lowStockCount = products.filter(p => p.status === 'low_stock').length;
  const outOfStockCount = products.filter(p => p.status === 'out_of_stock').length;
  const criticalAlertsCount = alerts.filter(a => a.status === 'active' && a.severity === 'critical').length;

  return {
    totalInventoryValue,
    totalSKUs,
    inStockCount,
    lowStockCount,
    outOfStockCount,
    criticalAlertsCount,
    activePurchaseOrders: 3,
    monthlyTurnoverRate: 4.2
  };
}

